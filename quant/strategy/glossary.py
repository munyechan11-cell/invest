def describe(table: dict[str, Term], key: str) -> dict:
    """사전에 없으면 영어 이름을 그대로 내보냅니다.

    설명이 없다고 화면이 비면 안 됩니다 — 모르는 부품이 하나 생겼을 때
    나머지 목록까지 사라지는 것이 훨씬 나쁩니다.
    """
    term = table.get(key)
    if term is None:
        return {"id": key, "ko": key, "what": "", "kind": "signal"}
    return {"id": key, "ko": term.ko, "what": term.what, "kind": term.kind}
